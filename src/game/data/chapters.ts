/*
 * Map legend
 *   .  plains     r  road       F  forest (+1 def, +20 avo, slow)
 *   h  hills (+2 def, +30 avo, very slow)      D  desert (very slow, no bonus)
 *   M  mountain (fliers only)   W  water (fliers only)   #  wall
 *   H  fort (+2 def, +20 avo, heals 20%/turn)
 *   B  bridge     T  throne (+3 def, +30 avo, heals)
 *   V  house (visit once for its reward, listed in `houses`)   b  building (impassable)
 *   x  ruins (+1 def, +10 avo, slow): burned-out buildings, scenery
 *   C  treasure chest (contents listed in `chests`)   d  locked door   G  locked gate
 *   Chests, doors and gates each take one key (any unit) or one lockpick (thieves) to open.
 *   Enemies with `key: true` carry a key; whoever defeats them takes it, and unused keys stay in that unit's pack.
 *   Never lock the objective away: a door or gate may only guard optional rooms, or the map can become unwinnable.
 * Only put houses where the story has people living: a village being raided, a castle town,
 * a hermit's cabin. Enemies with ai 'raid' walk to the nearest open house and burn it.
 * Maps can be any size; the battle view scrolls. Chapters are 22 x 14: the original 14 x 10
 * battlefield is the top-left, with the town and countryside around it to the east and south. Player starts are listed in deployment order (Lord first).
 */
